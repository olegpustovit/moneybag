// The canonical form always parses back to itself, including leap days.
for(const r of [{from:d('2024-02-29'),to:d('2024-03-01')},{from:d('2023-01-01'),to:d('2026-10-30')}])assert.equal(show(parseRange(canonicalText(r),b)),show(r))
