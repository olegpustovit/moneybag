import { chromium } from 'playwright'
import { existsSync } from 'node:fs'
import assert from 'node:assert/strict'

const browser=await chromium.launch({executablePath:process.env.CHROMIUM_BIN || (existsSync(process.env.HOME+'/.nix-profile/bin/chromium') ? process.env.HOME+'/.nix-profile/bin/chromium' : undefined),args:['--no-sandbox']})
const context=await browser.newContext({viewport:{width:390,height:900}})
const lines=Array.from({length:240},(_,i)=>({id:`line${i}`,revision:1,name:`Line ${i}`,limit:10,limit_exact:'10',actual:1,avg6:1,status:'within',accounts:[],literal_accounts:[],group_ref:i%2 ? {dimension:'category',value:'A longer category'} : undefined}))
await context.route('**/api/session',route=>route.fulfill({json:{user:{id:'synthetic',name:'Alex',email:'alex@example.test',is_admin:true},csrf:'test',version:'test',mcp_url:'/api/mcp'}}))
await context.route('**/api/mcp',route=>{const req=route.request().postDataJSON(),name=req.params.name;let result;if(req.method==='server/discover')result={supportedVersions:['2026-07-28']};else if(name==='dashboard_list'||name==='db_list')result={structuredContent:{items:[]}};else if(name==='budget_get')result={structuredContent:{month:'2026-10',window:{months:6,label:'Apr–Sep'},lines,total:{id:'total',name:'Total',limit:2400,actual:240,avg6:240,status:'within',accounts:[],literal_accounts:[]},unmapped:[]}};else throw Error(name);return route.fulfill({json:{jsonrpc:'2.0',id:req.id,result}})})
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://127.0.0.1:5173/budgets')
const grid=page.getByRole('region',{name:'Budget lines'})
await grid.getByRole('button',{name:'Edit Name for Line 0'}).waitFor()
assert((await grid.locator('tbody tr').count())<=60)
await grid.evaluate(el=>{el.scrollTop=el.scrollHeight})
await grid.getByRole('button',{name:'Edit Name for Line 239'}).waitFor()
assert((await grid.locator('tbody tr').count())<=60)
await grid.getByRole('button',{name:'Edit Name for Line 239'}).click()
await grid.getByLabel('Name for Line 239').fill('Unsaved')
await grid.getByLabel('Name for Line 239').press('Escape')
await grid.getByRole('button',{name:'Edit Name for Line 239'}).waitFor()
assert.deepEqual(errors,[])
await context.close()
await browser.close()
console.log('budget variable-height virtualization passed')
